plt.ylabel('Total People')
plt.title('Total People in Each age Decate')
# ser x-axis ticks to only show the decades
plt.xticks(list(total.keys()))
plt.show()

# barchart for purchases made by each age decade

plt.figure(figsize=(8, 6))
plt.bar(total.keys(), purchases.values())
plt.xlabel('Age Decade')
plt.ylabel('Purchases Made')
plt.title('Purchases Made by Each age Decade')
# ser x-axis ticks to only show the decades
plt.xticks(list(purchases.keys()))
plt.show()

"""Conditional Probability"""

# compute P(A|B), where A is "purchase" and B is "the person in it's 50's"
PAB=float(purchases[50])/float(total[50])
print('P(purchase|50s): ' +str(PAB))

# compute P(B) means the probability of being 50 in the dataset
PB= float(total[50])/50000.0
print('P(50s): ' +str(PB))

# compute p(A) means the overall probability of buying something, regardless of its age
PA= float(totalPurchases)/50000.0
print('P(perchase): ' +str(PA))

#  P(A|B) = P(A,B)/ P(A)

# Compute P(A,B) where it is the probability of both being in its 50's and buying something P(A,B) out of the total population
print('P(50s, purchase ): ' +str(float(purchases[50]) / 50000.0))

# compute the overall probability of buying something and the overall probability of being in 50's
print('P(50s) P(purchase): ' +str(PA*PB))

