# Import libraries
import numpy as np
import matplotlib.pyplot as plt
from numpy import random

# Generate a seed value for a random number of generator
random.seed(0)

# total indicates the total no of people is in each age range
total={20:0, 30:0, 40:0, 50:0, 60:0}
#purchases indicates the total no of purchases were made by each person in these age range
purchases={20:0, 30:0, 40:0, 50:0, 60:0}
# total number of purchases regardless of age
totalPurchases=0

# create a loop to iterate through 50000 radom people.
for _ in range(50000):
  ageDecade=random.choice([20, 30, 40, 50, 60])
  # Compute a purchase probability given by the age
  purchaseProbability=float(ageDecade) / 100.0
  # collect the total for the generated age decade
  total[ageDecade] +=1
  # check the person bought something if random number is less than the purchase probability
  if(random.random() < purchaseProbability):
    # total number of purchases that are done across the entire dataset
    totalPurchases +=1
    # track of purchases for the individual age decade
    purchases[ageDecade] +=1

